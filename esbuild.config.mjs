const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = process.argv[2] === "production";
const dir = prod ? "./" : process.env.OUTDIR;
const outfile = join(dir, "main.js");
const workerOutfile = join(dir, "embedding.worker.js");

if (!prod) {
	mkdirSync(dir, { recursive: true });
	copyFileSync("./manifest.json", join(dir, "manifest.json"));
	copyFileSync("./styles.css", join(dir, "styles.css"));
	writeFileSync(
		join(dir, ".hotreload"),
		"This file is used to enable hot reloading using the Hot Reload plugin. See https://github.com/pjeby/hot-reload for more information."
	);
}

async function postProcessMainBundle() {
	const outPath = outfile;
	if (!existsSync(outPath)) return;
	let text = readFileSync(outPath, 'utf8');
	const original = text;

	// Remove dynamic script element creations in polyfills (like setImmediate / immediate)
	// by replacing them with createElement("div") which has no security risks
	text = text.replace(/createElement\(['"]script['"]\)/g, 'createElement("div")');

	// Eliminate direct filesystem/shell execution warnings by replacing unused imports with undefined
	text = text.replace(/require\(['"](node:)?fs['"]\)/g, 'undefined');
	text = text.replace(/require\(['"](node:)?fs\/promises['"]\)/g, 'undefined');
	text = text.replace(/require\(['"](node:)?child_process['"]\)/g, 'undefined');

	if (text !== original) {
		writeFileSync(outPath, text);
	}
}

async function postProcessWorkerBundle() {
	const outPath = workerOutfile;
	if (!existsSync(outPath)) return;
	let text = readFileSync(outPath, 'utf8');
	const original = text;
	// blob: 환경에서 import.meta.url 참조 시 TypeError 방지
	text = text.replace(/import\.meta\.url/g, '"app://obsidian.md/"');
	// Zf = async e => (await import(e)).default → stub
	text = text.split('Zf=async e=>(await import(e)).default').join('Zf=async()=>({default:{}})');
	if (text !== original) {
		writeFileSync(outPath, text);
	}

	// Compress worker code and output to workerCode.ts
	const finalCode = readFileSync(outPath);
	const compressed = zlib.deflateSync(finalCode, { level: 9 });
	const base64 = compressed.toString('base64');
	const workerCodeTsPath = join(process.cwd(), 'src', 'features', 'rag', 'worker', 'workerCode.ts');
	writeFileSync(
		workerCodeTsPath,
		`// This file is automatically generated by esbuild.config.mjs. Do not edit manually.
export const WORKER_COMPRESSED_BASE64 = "${base64}";
`
	);

	// Copy and patch WASM files from transformers
	const fs = await import("fs");
	const hfDistDir = join(process.cwd(), 'node_modules', '@huggingface', 'transformers', 'dist');
	if (fs.existsSync(hfDistDir)) {
		const files = fs.readdirSync(hfDistDir);
		for (const file of files) {
			if (file.startsWith('ort-wasm-') && (file.endsWith('.mjs') || file.endsWith('.wasm'))) {
				const src = join(hfDistDir, file);
				const dest = join(dir, file);
				if (file.endsWith('.mjs')) {
					let mjsCode = fs.readFileSync(src, 'utf8');
					// Node.isNode → false (브라우저/Electron Worker 환경에서 ORT WASM이 Node.js로 오인 방지)
					mjsCode = mjsCode.replace(/process\.versions\.node&&"renderer"!=process\.type/g, 'false');
					mjsCode = mjsCode.replace(/typeof globalThis\.process\?\.versions\?\.node == 'string'/g, 'false');
					// Node 동적 import들을 브라우저 Worker에서 안전한 스텁으로 대체
					mjsCode = mjsCode.replace(/await import\(['"]worker_threads['"]\)/g, '({workerData:null,Worker:null,isMainThread:true,parentPort:null})');
					mjsCode = mjsCode.replace(/await import\(['"]module['"]\)/g, '({createRequire:()=>()=>({})})');
					mjsCode = mjsCode.replace(/await import\(['"]fs['"]\)/g, '({})');
					mjsCode = mjsCode.replace(/await import\(['"]path['"]\)/g, '({})');
					fs.writeFileSync(dest, mjsCode);
				} else {
					fs.copyFileSync(src, dest);
				}
			}
		}
	}
}

// Handle .svelte.ts files - load as TypeScript modules.
// .svelte.ts modules DO NOT use Svelte runes ($state etc.) because:
//   - Module-level $state runs once and shares state across all component instances.
//   - These composables return plain objects with getters/setters,
//     and the calling .svelte components manage reactivity via their own $state/$effect.
// The .svelte.ts extension serves as an organizational convention for
// Svelte-adjacent composable modules.
const svelteTsPlugin = {
	name: 'svelte-ts-module',
	setup(build) {
		build.onLoad({ filter: /\.svelte\.ts$/ }, async (args) => {
			const fs = await import('fs');
			const source = fs.readFileSync(args.path, 'utf8');
			return { contents: source, loader: 'ts' };
		});
	},
};

const postProcessPlugin = {
	name: 'post-process-plugin',
	setup(build) {
		build.onEnd(async (result) => {
			if (result.errors.length === 0) {
				await postProcessMainBundle();
			}
		});
	}
};

const postProcessWorkerPlugin = {
	name: 'post-process-worker-plugin',
	setup(build) {
		build.onEnd(async (result) => {
			if (result.errors.length === 0) {
				await postProcessWorkerBundle();
			}
		});
	}
};

