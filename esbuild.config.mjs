// ─── Build 2: Embedding Worker Bundle (iife) ─────────────────────────────
//
// IIFE 포맷 이유:
//   @xenova/transformers 내부에서 import.meta.url 로 ONNX WASM 파일 경로를 계산함.
//   CJS로 번들하면 import.meta.url이 'undefined'가 되어 WASM 로드 실패.
//   IIFE로 번들하고, import.meta.url 은 플러그인으로 더미 값으로 치환.
//   (ONNX WASM 경로는 embedding.worker.ts 에서 CDN으로 명시 지정됨)
//
// ⚠️ @xenova/transformers 는 번들에 포함 (external에서 제외).
//    obsidian, electron, Node built-ins 만 external 처리.
//
// process 폴리필: Electron 환경 Worker에서 process가 null인 경우 방지.
//   런타임 문자열 삽입 대신 빌드타임에 banner로 주입.
const workerProcessPolyfill = `
// Node 환경 감지 우회: ORT WASM이 Node.js 환경으로 오인하고 worker_threads를 import하는 것을 방지.
// (CDN에서 로드되는 .mjs 파일 내부의 isNode 검사 로직 무력화)
if (typeof globalThis.process !== 'undefined') {
	try {
		let fakeProcess = { ...globalThis.process };
		fakeProcess.type = 'renderer';
		fakeProcess.versions = { ...(globalThis.process.versions || {}), node: undefined };
		Object.defineProperty(globalThis, 'process', { value: fakeProcess, configurable: true, writable: true });
	} catch (e) {
		console.warn("Failed to overwrite global process", e);
	}
}
if (typeof process === 'undefined' || process === null) {
	self.process = { env: {}, on: function() {}, argv: [], versions: {} };
} else {
	if (!process.on) process.on = function() {};
}
`;

// Node 전용 모듈을 브라우저 Worker 환경에서 빈 스텁으로 대체
const workerNodeStubs = {
	name: 'stub-node-builtins',
	setup(build) {
		// transformers.js v3 내부에서 조건적으로 import하는 Node 전용 모듈들을 가로챔
		build.onResolve({ filter: /^(worker_threads|perf_hooks|tty|os|fs|path)$/ }, (args) => ({
			path: args.path,
			namespace: 'node-stub',
		}));
		build.onLoad({ filter: /.*/, namespace: 'node-stub' }, (args) => {
			if (args.path === 'worker_threads') {
				return { contents: 'export const isMainThread = true; export const parentPort = null; export const Worker = null; export default {};' };
			}
			return { contents: 'export default {};' };
		});
	},
};

const workerContext = await esbuild.context({
	entryPoints: ["src/features/rag/worker/embedding.worker.ts"],
	bundle: true,
	format: "iife",
	target: "es2020",
	logLevel: "info",
	sourcemap: false,
	minify: true,
	treeShaking: true,
	banner: { js: workerProcessPolyfill },
	// obsidian / electron 은 워커에서 사용 불가 — external 처리
	// Note: Node built-ins(fs, path 등)은 external에 넣으면 브라우저용 worker 빌드 시
	// bare import("fs")가 생성되어 에러를 유발합니다. 제거하여 package.json의 browser 필드가 작동하게 합니다.
	external: obsidianExternals.filter(e => !builtinModules.includes(e) && !e.startsWith("node:")),
	outfile: workerOutfile,
	plugins: [workerNodeStubs, postProcessWorkerPlugin],
	define: {
		// 불필요한 Node 환경 체크 우회
		'process.env.NODE_ENV': '"production"',
		'process.release.name': '"browser"',
	},
});

// ─── Watch / Build ────────────────────────────────────────────────────────────
if (prod) {
	await workerContext.rebuild();
	const result = await mainContext.rebuild();
	const fs = await import("fs");
	if (result && result.metafile) fs.writeFileSync('meta.json', JSON.stringify(result.metafile));
	process.exit(0);
} else {
	await workerContext.rebuild();
	await mainContext.rebuild();
	await Promise.all([mainContext.watch(), workerContext.watch()]);
}
